"""
Generates sql/02_load_data.sql - plain INSERT statements for every CSV row.

Why: pgAdmin's Query Tool cannot run psql's \\copy, and a server-side COPY needs
file permissions on the Postgres server. INSERTs run anywhere with zero setup.

Usage (from repo root, after export_excel_to_csv.py):
    python scripts/generate_insert_sql.py
"""
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CSV_DIR, OUT = ROOT / "data" / "csv", ROOT / "sql" / "02_load_data.sql"

TABLES = [  # (csv file, staging table)
    ("sales_weekly.csv", "staging.sales_weekly_raw"),
    ("shopper_profile_appeal.csv", "staging.shopper_profile_raw"),
    ("variable_definitions.csv", "staging.variable_definitions_raw"),
    ("customer_complaints.csv", "staging.customer_complaints_raw"),
]
BATCH = 200

def lit(v: str) -> str:
    return "NULL" if v == "" else "'" + v.replace("'", "''") + "'"

lines = [
    "-- =====================================================================",
    "-- STEP 02 - Load raw data into staging (AUTO-GENERATED - do not edit)",
    "-- Generated by scripts/generate_insert_sql.py from data/csv/*.csv",
    "-- Runs in pgAdmin Query Tool (F5). Re-runnable: tables are truncated first.",
    "-- =====================================================================",
    "BEGIN;",
]
for fname, table in TABLES:
    with open(CSV_DIR / fname, newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))[1:]
    lines += ["", f"-- {table}: {len(rows)} rows from {fname}", f"TRUNCATE {table};"]
    for i in range(0, len(rows), BATCH):
        chunk = rows[i:i + BATCH]
        lines.append(f"INSERT INTO {table} VALUES")
        lines.append(",\n".join("(" + ",".join(lit(v) for v in r) + ")" for r in chunk) + ";")
lines += ["", "COMMIT;", ""]
OUT.write_text("\n".join(lines), encoding="utf-8")
print(f"wrote {OUT} ({OUT.stat().st_size/1024:.0f} KB)")
